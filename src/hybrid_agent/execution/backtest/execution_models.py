"""Execution models, protocols, classifications, and canonical fill results for FillEngine.

Provides:
- LiquiditySide: MAKER, TAKER, UNKNOWN classification.
- ExecutionProvenance: REAL_QUOTE, SYNTHETIC_BAR provenance.
- FillCandidate: Canonical immutable fill result linking Decimal-based FillRecord with
  immutable OrderSnapshot, completion status, diagnostics, and lossless Portfolio event conversion.
- Protocols for SpreadModel, SlippageModel, CommissionModel, and LiquidityModel.
- Custom exception types for matching and execution cost calculations.
"""

from collections.abc import Sequence
from dataclasses import dataclass, field
from decimal import Decimal
from enum import Enum
from typing import Protocol, runtime_checkable

from hybrid_agent.core.constants import OrderSide
from hybrid_agent.core.models import (
    Bar,
    InstrumentSpecification,
    Order,
    Quote,
    Tick,
)
from hybrid_agent.execution.backtest.events import (
    OrderFilledEvent,
    OrderPartiallyFilledEvent,
)
from hybrid_agent.execution.backtest.state import FillRecord, OrderSnapshot


class FillEngineError(Exception):
    """Base exception class for all FillEngine and execution matching errors."""


class DuplicateMarketEventError(FillEngineError):
    """Raised when a market data event is re-submitted with duplicate event identity."""


class UnsupportedOrderTypeError(FillEngineError, ValueError):
    """Raised when an order type is unsupported or cannot be matched by FillEngine."""


class InvalidModelConfigurationError(FillEngineError, ValueError):
    """Raised when an execution cost model receives invalid, negative, or contradictory parameters."""


class LiquidityExhaustedError(FillEngineError):
    """Raised when market data contains zero available liquidity under a strict reject policy."""


class LiquiditySide(str, Enum):
    """Maker / taker liquidity classification for market orders and executions."""

    MAKER = "MAKER"
    TAKER = "TAKER"
    UNKNOWN = "UNKNOWN"


class ExecutionProvenance(str, Enum):
    """Execution origin classification indicating matching evidence source."""

    REAL_QUOTE = "REAL_QUOTE"
    SYNTHETIC_BAR = "SYNTHETIC_BAR"


@dataclass(frozen=True)
class FillCandidate:
    """Canonical immutable execution fill result generated by FillEngine.

    Contains the authoritative Decimal-based FillRecord for OrderManager synchronization,
    order snapshot metadata, liquidity classification, execution provenance, and diagnostics.
    Provides direct lossless adaptation to Portfolio accounting events without recalculation.
    """

    fill_record: FillRecord
    order_snapshot: OrderSnapshot
    is_complete: bool
    liquidity_side: LiquiditySide
    provenance: ExecutionProvenance
    market_event_id: str
    diagnostics: tuple[str, ...] = field(default_factory=tuple)

    def __post_init__(self) -> None:
        if not isinstance(self.fill_record, FillRecord):
            raise TypeError(
                f"fill_record must be a FillRecord instance, got {type(self.fill_record).__name__}"
            )
        if not isinstance(self.order_snapshot, OrderSnapshot):
            raise TypeError(
                f"order_snapshot must be an OrderSnapshot instance, got {type(self.order_snapshot).__name__}"
            )
        if not isinstance(self.liquidity_side, LiquiditySide):
            raise TypeError(
                f"liquidity_side must be a LiquiditySide enum, got {type(self.liquidity_side).__name__}"
            )
        if not isinstance(self.provenance, ExecutionProvenance):
            raise TypeError(
                f"provenance must be an ExecutionProvenance enum, got {type(self.provenance).__name__}"
            )
        if not self.market_event_id or not isinstance(self.market_event_id, str):
            raise ValueError("market_event_id must be a non-empty string")
        if not isinstance(self.diagnostics, tuple):
            object.__setattr__(self, "diagnostics", tuple(self.diagnostics))

    @property
    def order_id(self) -> str:
        """Convenience property accessing the filled order's unique ID."""
        return self.order_snapshot.id

    @property
    def symbol(self) -> str:
        """Convenience property accessing the filled instrument symbol."""
        return self.fill_record.symbol

    @property
    def side(self) -> OrderSide:
        """Convenience property accessing the order side."""
        return self.fill_record.side

    @property
    def fill_price(self) -> Decimal:
        """Authoritative execution price."""
        return self.fill_record.fill_price

    @property
    def fill_quantity(self) -> Decimal:
        """Authoritative executed quantity."""
        return self.fill_record.fill_quantity

    def to_domain_order(self) -> Order:
        """Constructs a domain Order instance from the immutable order snapshot."""
        return Order(
            id=self.order_snapshot.id,
            symbol=self.order_snapshot.symbol,
            side=self.order_snapshot.side,
            order_type=self.order_snapshot.order_type,
            quantity=self.order_snapshot.quantity,
            limit_price=self.order_snapshot.limit_price,
            stop_loss_price=self.order_snapshot.stop_loss_price,
            take_profit_price=self.order_snapshot.take_profit_price,
            status=self.order_snapshot.status,
            created_at=self.order_snapshot.created_at,
            updated_at=self.order_snapshot.updated_at,
        )

    def to_portfolio_event(self) -> OrderFilledEvent | OrderPartiallyFilledEvent:
        """Adapts the canonical fill result directly to the existing Portfolio event interface.

        Derives all fields directly from the canonical FillRecord and OrderSnapshot without
        re-evaluating or recalculating matching prices, quantities, fees, or slippage.
        """
        domain_order = self.to_domain_order()
        price_float = float(self.fill_record.fill_price)
        quantity_float = float(self.fill_record.fill_quantity)
        fee_float = float(self.fill_record.fee)
        slippage_float = float(self.fill_record.slippage)
        ts = self.fill_record.timestamp

        if self.is_complete:
            return OrderFilledEvent(
                order=domain_order,
                fill_price=price_float,
                fill_quantity=quantity_float,
                fee=fee_float,
                slippage=slippage_float,
                timestamp=ts,
            )
        return OrderPartiallyFilledEvent(
            order=domain_order,
            fill_price=price_float,
            fill_quantity=quantity_float,
            fee=fee_float,
            slippage=slippage_float,
            timestamp=ts,
        )


@runtime_checkable
class SpreadModel(Protocol):
    """Protocol for bid/ask spread calculation."""

    def calculate_half_spread(
        self,
        symbol: str,
        reference_price: Decimal,
        spec: InstrumentSpecification | None = None,
    ) -> Decimal:
        """Calculates half-spread to apply to reference price."""
        ...

    def calculate_spread(
        self,
        symbol: str,
        reference_price: Decimal,
        spec: InstrumentSpecification | None = None,
    ) -> Decimal:
        """Calculates full bid/ask spread."""
        ...


@runtime_checkable
class SlippageModel(Protocol):
    """Protocol for adverse slippage impact calculation."""

    def calculate_slippage(
        self,
        order: OrderSnapshot,
        base_price: Decimal,
        fill_quantity: Decimal,
        market_data: Quote | Tick | Bar,
        spec: InstrumentSpecification | None = None,
    ) -> Decimal:
        """Calculates non-negative adverse price delta.

        For BUY: execution_price = base_price + slippage.
        For SELL: execution_price = base_price - slippage.
        """
        ...


@runtime_checkable
class CommissionModel(Protocol):
    """Protocol for execution fee and commission calculation."""

    def calculate_commission(
        self,
        order: OrderSnapshot,
        fill_price: Decimal,
        fill_quantity: Decimal,
        spec: InstrumentSpecification | None = None,
    ) -> tuple[Decimal, str | None]:
        """Calculates execution commission and explicit currency.

        Returns:
            Tuple of (commission_amount, commission_currency).
            If commission_amount > 0, commission_currency must be a non-empty string.
        """
        ...

    def reset(self) -> None:
        """Resets any internal order commission tracking state."""
        ...


@runtime_checkable
class LiquidityModel(Protocol):
    """Protocol for quote depth and bar volume participation management."""

    def get_available_quote_liquidity(
        self,
        quote: Quote | Tick,
        side: OrderSide,
        market_event_id: str,
    ) -> tuple[Decimal, Sequence[str]]:
        """Returns currently available quote displayed size and any diagnostics."""
        ...

    def get_available_bar_liquidity(
        self,
        bar: Bar,
        market_event_id: str,
    ) -> tuple[Decimal, Sequence[str]]:
        """Returns currently available bar participation volume and any diagnostics."""
        ...

    def consume_quote_liquidity(
        self,
        market_event_id: str,
        symbol: str,
        side: OrderSide,
        quantity: Decimal,
    ) -> None:
        """Consumes a portion of available quote liquidity for a market event."""
        ...

    def consume_bar_liquidity(
        self,
        market_event_id: str,
        symbol: str,
        quantity: Decimal,
    ) -> None:
        """Consumes a portion of available bar participation volume for a market event."""
        ...

    def reset(self) -> None:
        """Resets all consumed liquidity state."""
        ...
